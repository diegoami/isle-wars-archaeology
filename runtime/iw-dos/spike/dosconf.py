"""The DOSBox-X configuration of an E003 run: generated here, and checked before every launch.

DOSBox-X mounts host directories only through its configuration and its command line: `mount` and
`imgmount` in [autoexec] or in a `-c` command, `automountall`, and the drives it adds itself (Z:,
its own virtual drive, holds no host file). A run's configuration is generated by `generate` and
then checked by `problems`, which accepts only what `generate` writes:
- [autoexec] holds exactly one `mount`, of drive C, of the run copy (the canonical path), and every
  other line is one of a short list (echo off, date, time, `c:`, the game, `exit`); `imgmount`, `subst`, a second mount and any other line abort the run;
- the settings that would mount, network or open a host path are fixed: automountall and startcmd
  off; IPX, NE2000, every serial and parallel port, the printer off; captures, savefile and
  mapperfile inside the run's private work directory;
- the command line names that configuration only, and no `-c`, `-set`, `-conf` or other mount.

N0 (DOSBox-X's networking off) is part of the same check. Sound is off: no mixer output, no PC
speaker, Sound Blaster, Gravis or MIDI device.
"""
import re
from pathlib import PurePosixPath

GAME = "ISLEWAR"
DRIVE = "c"

# Settings that are fixed for every run, by section. `problems` requires each of them.
FIXED = {
    "sdl": {"fullscreen": "false", "output": "surface", "autolock": "false",
            "mouse_emulation": "never"},
    "dosbox": {"saveremark": "false", "quit warning": "false"},
    "mixer": {"nosound": "true"},
    "speaker": {"pcspeaker": "false"},
    "sblaster": {"sbtype": "none"},
    "gus": {"gus": "false"},
    "midi": {"mpu401": "none", "mididevice": "none"},
    "serial": {f"serial{n}": "disabled" for n in (1, 2, 3, 4)},
    "parallel": {f"parallel{n}": "disabled" for n in (1, 2, 3)},
    "printer": {"printer": "false"},
    "ipx": {"ipx": "false"},
    "ne2000": {"ne2000": "false"},
    "dos": {"automountall": "false", "startcmd": "false"},
}
# Settings that name a host path; each must lie inside the work directory.
PATH_SETTINGS = {("sdl", "mapperfile"), ("dosbox", "captures"), ("dosbox", "savefile")}
# Settings an arm may choose; anything not listed here or in FIXED is refused.
FREE = {("cpu", "cycles"), ("dosbox", "synchronize time")}
CYCLES = re.compile(r"(fixed \d{3,6}|max|auto)")
AUTOEXEC_OTHER = [
    re.compile(r"@echo off"),
    re.compile(r"date \d{2}-\d{2}-\d{4}"),
    re.compile(r"time \d{2}:\d{2}:\d{2}"),
    re.compile(r"c:"),
    re.compile(GAME),
    re.compile(r"exit"),
]
# -break-start asks for DOSBox-X's debugger at start; the debugger arm passes it (this build has
# none, so it changes nothing: exploration round 2, `dbg-breakstart`).
ALLOWED_FLAGS = ("-nogui", "-nomenu", "-fastlaunch", "-nopromptfolder", "-defaultmapper", "-break-start")


def quote(path):
    text = str(path)
    if '"' in text or "\n" in text:
        raise ValueError("a path with a quote or a newline cannot be put in a DOSBox-X configuration")
    return f'"{text}"'


def generate(game_dir, workdir, cycles="fixed 3000", clock=None):
    """The configuration text. `clock` is None (DOSBox-X follows the host's clock) or a
    ("MM-DD-YYYY", "HH:MM:SS") pair set in [autoexec] with the host synchronisation off."""
    work = PurePosixPath(workdir)
    sections = {k: dict(v) for k, v in FIXED.items()}
    sections["sdl"]["mapperfile"] = str(work / "mapper.map")
    sections["dosbox"]["captures"] = str(work / "cap")
    sections["dosbox"]["savefile"] = str(work / "save" / "state.sav")
    sections["dosbox"]["synchronize time"] = "false" if clock else "true"
    sections["cpu"] = {"cycles": cycles}
    lines = []
    for name, values in sections.items():
        lines.append(f"[{name}]")
        lines += [f"{key}={value}" for key, value in values.items()]
    lines += ["[autoexec]", "@echo off", f"mount {DRIVE} {quote(game_dir)}"]
    if clock:
        lines += [f"date {clock[0]}", f"time {clock[1]}"]
    lines += [f"{DRIVE}:", GAME, "exit"]
    return "\n".join(lines) + "\n"


def parse(text):
    """({section: {key: value}}, [autoexec lines]) of a configuration text; ValueError on a line
    outside any section, a repeated setting or a line that is not `key=value`."""
    sections, autoexec, current = {}, [], None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"\[([a-z0-9_ ]+)\]", line, re.IGNORECASE)
        if match:
            current = match.group(1).lower()
            if current != "autoexec":
                if current in sections:
                    raise ValueError(f"section [{current}] appears twice")
                sections[current] = {}
            continue
        if current is None:
            raise ValueError("a line outside any section")
        if current == "autoexec":
            autoexec.append(line)
            continue
        if "=" not in line:
            raise ValueError(f"[{current}] has a line that is not key=value")
        key, value = (part.strip() for part in line.split("=", 1))
        key = key.lower()
        if key in sections[current]:
            raise ValueError(f"[{current}] {key} is set twice")
        sections[current][key] = value
    return sections, autoexec


def inside(path, directory):
    path, directory = PurePosixPath(path), PurePosixPath(directory)
    return path.is_absolute() and ".." not in path.parts and directory in path.parents


def problems(text, game_dir, workdir, command=None):
    """Why a configuration (and the DOSBox-X command line naming it) may not be launched; [] when
    it may. `game_dir` is the canonical run copy, the only directory that may be mounted."""
    try:
        sections, autoexec = parse(text)
    except ValueError as exc:
        return [f"the configuration cannot be read: {exc}"]
    found = []
    for section, values in FIXED.items():
        for key, want in values.items():
            have = sections.get(section, {}).get(key)
            if have is None or have.lower() != want:
                found.append(f"[{section}] {key} must be {want}, not {have!r}")
    for section, values in sections.items():
        for key, value in values.items():
            if key in FIXED.get(section, {}):
                continue
            if (section, key) in PATH_SETTINGS:
                if not inside(value, workdir):
                    found.append(f"[{section}] {key} names a path outside the run's work directory")
            elif (section, key) == ("cpu", "cycles"):
                if not CYCLES.fullmatch(value):
                    found.append(f"[cpu] cycles {value!r} is not a cycles setting this cycle uses")
            elif (section, key) in FREE:
                if value.lower() not in ("true", "false"):
                    found.append(f"[{section}] {key} must be true or false")
            else:
                found.append(f"[{section}] {key} is not a setting this cycle writes")
    mounts = []
    for line in autoexec:
        words = line.split(None, 2)
        verb = words[0].lower().lstrip("@") if words else ""
        if verb in ("mount", "imgmount", "subst", "imgmake", "mountiso", "drivezip"):
            mounts.append(line)
            continue
        if not any(p.fullmatch(line) for p in AUTOEXEC_OTHER):
            found.append(f"[autoexec] line {line!r} is not one this cycle writes")
    want = f"mount {DRIVE} {quote(game_dir)}"
    if mounts != [want]:
        found.append(f"[autoexec] must mount the run copy as {DRIVE.upper()}: and nothing else; it has "
                     f"{len(mounts)} mount line(s)" + ("" if len(mounts) != 1 else ", not of the run copy"))
    if command is not None:
        found += command_problems(command, workdir)
    return found


def command_problems(command, workdir):
    """The DOSBox-X command line may name one configuration in the work directory, and flags from
    ALLOWED_FLAGS; nothing that runs a command, sets a setting or loads another configuration."""
    found = []
    if not command or PurePosixPath(command[0]).name != "dosbox-x":
        return ["the command does not start DOSBox-X"]
    rest = list(command[1:])
    confs = [i for i, word in enumerate(rest) if word == "-conf"]
    if len(confs) != 1 or confs[0] + 1 >= len(rest) or not inside(rest[confs[0] + 1], workdir):
        return ["the command must name exactly one configuration, in the work directory"]
    del rest[confs[0]:confs[0] + 2]
    for word in rest:
        if word not in ALLOWED_FLAGS:
            found.append(f"the command line has {word!r}, which this cycle does not pass")
    return found
