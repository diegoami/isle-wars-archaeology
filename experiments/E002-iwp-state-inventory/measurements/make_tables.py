#!/usr/bin/env python3
"""Write measurements/run-table.md and measurements/file-bytes.md from runs/E002/*.json.

Only reads the run records, so the tables can be regenerated from a clean clone:
    python3 experiments/E002-iwp-state-inventory/measurements/make_tables.py
"""
import datetime
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))


def when(text):
    return datetime.datetime.strptime(text, "%Y-%m-%dT%H:%M:%SZ")


def first(obs, prefix):
    for o in obs:
        if str(o["field"]).startswith(prefix):
            return o["value"]
    return ""


def all_of(obs, prefix):
    return [o["value"] for o in obs if str(o["field"]).startswith(prefix)]


records = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(ROOT, "runs", "E002", "E002-r*.json")))]

lines = ["# E002 run table", "",
         "Generated by `make_tables.py` from `runs/E002/*.json`. Seconds are `ended` minus `started`.", "",
         "| run | arm | status | set | seconds | title screen after launch (s) | game exit status | wine processes gone after terminate (s) | script sha256 (first 16) |",
         "| --- | --- | --- | --- | ---: | ---: | --- | --- | --- |"]
for d in records:
    obs = d["observations"]
    secs = int((when(d["ended"]) - when(d["started"])).total_seconds())
    title = first(obs, "title screen reached")
    gone = first(obs, "wine processes gone after terminate")
    status = d["status"] if len(d["status"]) < 30 else d["status"][:27] + "..."
    lines.append(f"| {d['run_id']} | {d['arm']} | {status} | {d['artifact']['set']} | {secs} | {title} | "
                 f"{first(obs, 'game process exit status')} | {gone} | {str(first(obs, 'step script sha256'))[:16]} |")

lines += ["", "## Aborted runs, in full", ""]
for d in records:
    if not d["status"].startswith("completed"):
        lines.append(f"- {d['run_id']} ({d['arm']}): {d['status']}")

lines += ["", "## Waits on the game (settle), seconds", "",
          "| run | arm | settle observations (watched area unchanged for N s: seconds taken) |", "| --- | --- | --- |"]
for d in records:
    s = [str(v) for v in all_of(d["observations"], "settle: watched area unchanged for")]
    if s:
        lines.append(f"| {d['run_id']} | {d['arm']} | {', '.join(s)} |")
open(os.path.join(HERE, "run-table.md"), "w").write("\n".join(lines) + "\n")

out = ["# Bytes of the two files the game wrote, per run", "",
       "Generated by `make_tables.py`. The hex is the file as the game left it in the game copy (first N bytes, "
       "`raw:bytes[...]` observation of the run); `changed` is the driver's own diff against the install's file.", "",
       "| run | arm | file | size | hex | changed offsets (install to game copy) |", "| --- | --- | --- | ---: | --- | --- |"]
for d in records:
    obs = d["observations"]
    seen = {}
    for o in obs:
        f = str(o["field"])
        if f.startswith("raw:bytes"):
            name = f.split(" of ")[1].split(" ")[0]
            seen.setdefault(name, {})["hex"] = o["value"]
        elif ": size in bytes and sha256" in f and ("Isledft" in f or "Islepro.skr" in f):
            name = f.split(":")[0]
            seen.setdefault(name, {})["size"] = str(o["value"]).split()[0]
        elif ": changed byte offsets" in f:
            name = f.split(":")[0]
            seen.setdefault(name, {})["changed"] = o["value"]
    for name, v in seen.items():
        if "hex" in v:
            out.append(f"| {d['run_id']} | {d['arm']} | `{name}` | {v.get('size', '')} | `{v['hex']}` | {v.get('changed', '')} |")
open(os.path.join(HERE, "file-bytes.md"), "w").write("\n".join(out) + "\n")
print("wrote run-table.md and file-bytes.md for", len(records), "records")
